# перевод из десятичной системы в двоичную
n = int(input("Введите десятичное число: "))
#перевод с помощью функции bin
bin_num=bin(n)[2:]
#расчет вручную
bin_num1 = ""
while n:
    bin_num1 = str(n % 2) + bin_num1
    n = n//2
print(f"Перевод с помощью функции: {bin_num},перевод с помощью математического алгоритма: {bin_num1}")